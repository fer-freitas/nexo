def visible() -> list[CommandSpec]:
    return [s for s in COMMANDS if not s.hidden]


def top_levels() -> list[str]:
    seen: list[str] = []
    for spec in COMMANDS:
        if spec.top not in seen:
            seen.append(spec.top)
    return seen


def specs_for(top: str) -> list[CommandSpec]:
    return [s for s in COMMANDS if s.top == top]


def match(words: list[str]) -> CommandSpec | None:
    """Casa a sequência de palavras mais longa possível com um comando conhecido."""
    for size in range(len(words), 0, -1):
        path = " ".join(words[:size])
        for spec in COMMANDS:
            if spec.path == path:
                return spec
    return None
