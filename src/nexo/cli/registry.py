"""Fonte única da superfície de comandos: alimenta `nexo help` e o painel."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CommandSpec:
    path: str  # ex.: "plan feature"
    args: str
    group: str
    summary_pt: str
    summary_en: str
    hidden: bool = False  # atalho antigo ou uso interno — funciona, mas fica fora da ajuda e do painel
    alias_of: str = ""  # nome novo do comando (o antigo continua valendo)

    @property
    def top(self) -> str:
        return self.path.split(" ", 1)[0]

    def summary(self, lang: str) -> str:
        return self.summary_en if lang == "en" else self.summary_pt


